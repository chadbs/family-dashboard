  /* Written from the day itself. Each gets { temp, hi, condition, dinner,
     dinnerKind, weekday } and returns a note, or null when the day doesn't
     fit (no reading yet, wrong weather, nothing planned for dinner). */
  live: [
    function (d) {
      if (d.temp === null || d.temp > 32) return null;
      return "It's " + d.temp + "° outside this morning. Below freezing. And somehow you walked into the kitchen and warmed up the whole house. ❄️☕💚";
    },
    function (d) {
      if (!d.dinner || d.dinnerKind === "out" || d.dinnerKind === "leftovers") return null;
      return "Tonight's menu says " + d.dinner + ". Honestly, my favorite thing on the menu is the chef. 👩‍🍳💚";
    },
    function (d) {
      if (d.hi === null) return null;
      return "Today's high: " + d.hi + "°. My love for you today: no upper limit. 📈💚";
    },
    function (d) {
      if (!/rain|drizzle|shower|storm/i.test(d.condition)) return null;
      return "Rain in the forecast today. Doesn't matter — you're the sunshine in this house no matter what the sky is doing. 🌧️☀️💚";
    },
    function (d) {
      if (d.temp === null || d.temp <= 32 || d.temp >= 50) return null;
      return d.temp + "° and chilly this morning. Perfect weather for a sweater, a hot coffee, and a husband who can't stop thinking about you. 🧣☕💚";
    },
    function (d) {
      if (!d.dinner || d.dinnerKind === "out" || d.dinnerKind === "leftovers") return null;
      return "Thank you for planning dinner again — " + d.dinner + " tonight! You feed this family in every way there is. 🍽️💚";
    },
    function (d) {
      if (!/snow/i.test(d.condition)) return null;
      return "Snow today! The girls will want to be outside every minute, and I'll want to be inside with you every minute. Let's call it even. ❄️💚";
    },
    function (d) {
      if (d.temp === null || d.temp < 80) return null;
      return "It's already " + d.temp + "° out there, and it still isn't the hottest thing in this house. 🔥😄💚";
    },
    function (d) {
      if (d.dinnerKind !== "out") return null;
      return "Eating out tonight — a night off for the best cook in Michigan. You've earned it a hundred times over. 🍴💚";
    },
    function (d) {
      if (!/clear|sunny/i.test(d.condition)) return null;
      return "Clear skies over Hudsonville this morning, and the brightest thing under them is you. ☀️💚";
    },
    function (d) {
      return "Happy " + d.weekday + ", Kenzie. Just a reminder that I love you on " + d.weekday + "s too. And on every other day. 💚";
    },
  ],
